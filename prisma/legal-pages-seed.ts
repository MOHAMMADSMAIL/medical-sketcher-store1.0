async function main() {
  for (const page of PAGES) {
    const existing = await prisma.page.findUnique({ where: { slug: page.slug } });
    if (existing) {
      const nextVersion = (await prisma.pageVersion.aggregate({ where: { pageId: existing.id }, _max: { version: true } }))._max.version ?? 0;
      await prisma.$transaction([
        prisma.page.update({ where: { id: existing.id }, data: { title: page.title, status: 'DRAFT' } }),
        prisma.pageVersion.create({ data: { pageId: existing.id, version: nextVersion + 1, content: { sections: page.blocks } } }),
        prisma.section.deleteMany({ where: { pageId: existing.id } }),
        prisma.section.createMany({ data: page.blocks.map((block, index) => ({ pageId: existing.id, type: 'content', content: { order: index + 1, title: block.title, body: block.body } })) }),
      ]);
      console.log(`updated draft: ${page.slug}`);
    } else {
      await prisma.page.create({ data: { slug: page.slug, title: page.title, status: 'DRAFT', sections: { create: page.blocks.map((block, index) => ({ type: 'content', content: { order: index + 1, title: block.title, body: block.body } })) } } });
      console.log(`created draft: ${page.slug}`);
    }
  }
  await prisma.$disconnect();
}

main().catch((error) => { console.error(error); process.exit(1); });
